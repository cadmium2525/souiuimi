import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const base = process.env.GAME_URL || 'http://127.0.0.1:5173/';
const browser = await chromium.launch({ channel: 'chrome', args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'] });
const evidence = {};
const results = [];
const pass = name => { results.push(name); console.log(`PASS ${name}`); };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}?qa=1&fixture=original`);
  await page.waitForFunction(() => window.__game?.visuals);
  await page.waitForTimeout(300);
  evidence.title = await page.evaluate(() => window.__game.visuals());
  assert.equal(evidence.title.clueMarkers, 0);
  await page.screenshot({ path: 'artifacts/visual-title-v2.png', animations: 'disabled' });
  pass('title has no clue-location markers');
  await page.locator('[data-action=start]').click(); await page.locator('[data-action=explore]').click();
  await page.waitForTimeout(150);
  const idleBefore = await page.evaluate(() => window.__game.visuals());
  await page.waitForTimeout(700);
  const idleAfter = await page.evaluate(() => window.__game.visuals());
  assert.notEqual(idleBefore.hero.bodyY, idleAfter.hero.bodyY);
  pass('neutral idle breathing animates');
  await page.evaluate(() => window.__game.teleport(3.3, 3.5));
  await page.waitForFunction(() => window.__game.snapshot().x === 3.3);
  await page.keyboard.down('KeyW');
  await page.waitForFunction(() => Math.abs(window.__game.visuals().hero.leftKnee) + Math.abs(window.__game.visuals().hero.rightKnee) > 0.02);
  evidence.walk = await page.evaluate(() => window.__game.visuals());
  await page.screenshot({ path: 'artifacts/visual-walk-v2.png', animations: 'disabled' });
  await page.keyboard.up('KeyW');
  assert.equal(evidence.walk.clueMarkers, 0);
  assert.ok(evidence.walk.drawCalls < 120, JSON.stringify(evidence.walk));
  pass('articulated walk and bounded draw calls');
  await page.locator('[data-action=decision]').click(); await page.locator('[data-action=choose][data-detail=C]').click();
  await page.waitForTimeout(4500);
  evidence.cinematic = await page.evaluate(() => window.__game.visuals());
  await page.screenshot({ path: 'artifacts/visual-crane-v2.png', animations: 'disabled' });
  await page.waitForFunction(() => window.__game.snapshot().phase === 'ENDING');
  await page.locator('[data-action=retry]').click();
  assert.equal(await page.evaluate(() => window.__game.visuals().clueMarkers), 0);
  pass('storage choreography and marker-free retry');
  assert.deepEqual(errors, []);
  await context.close();
  const mobile = await browser.newContext({ viewport: { width: 360, height: 800 }, isMobile: true, hasTouch: true });
  const mobilePage = await mobile.newPage();
  await mobilePage.goto(`${base}?qa=1&fixture=original`);
  await mobilePage.waitForFunction(() => window.__game?.visuals);
  await mobilePage.locator('[data-action=start]').tap(); await mobilePage.locator('[data-action=explore]').tap();
  await mobilePage.evaluate(() => window.__game.teleport(3.3, 2.8));
  await mobilePage.waitForTimeout(300);
  await mobilePage.screenshot({ path: 'artifacts/visual-mobile-v2.png', animations: 'disabled' });
  pass('portrait composition with touch controls');
  await mobile.close();
  const reduced = await browser.newContext({ viewport: { width: 360, height: 800 }, reducedMotion: 'reduce' });
  const reducedPage = await reduced.newPage();
  await reducedPage.goto(`${base}?qa=1&fixture=original`);
  await reducedPage.waitForFunction(() => window.__game?.visuals);
  await reducedPage.locator('[data-action=start]').click(); await reducedPage.locator('[data-action=explore]').click();
  const quietBefore = await reducedPage.evaluate(() => window.__game.visuals().hero);
  await reducedPage.waitForTimeout(350);
  const quietAfter = await reducedPage.evaluate(() => window.__game.visuals().hero);
  for (const key of ['bodyY','leftKnee','rightKnee']) assert.ok(Math.abs(quietAfter[key] - quietBefore[key]) < 1e-9);
  pass('reduced-motion disables idle sway');
  await reduced.close();
} finally {
  await fs.writeFile('artifacts/visual-results.json', JSON.stringify({ browser: await browser.version(), results, evidence }, null, 2));
  await browser.close();
}
